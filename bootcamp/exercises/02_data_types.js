/*
 * WHAT ARE DATA TYPES?
 * Data types define what kind of value a variable holds - text, numbers, true/false, lists, or complex data.
 * JavaScript automatically determines the data type based on the value you assign.
 *
 * WHY DO WE NEED DATA TYPES?
 * 1. Different Operations: You can add numbers (5 + 3), but concatenate strings ("Hello" + "World")
 * 2. Memory Efficiency: Different types use different amounts of memory
 * 3. Prevent Errors: Trying to multiply text doesn't make sense - data types help catch mistakes
 * 4. Data Organization: Arrays hold lists, objects hold complex data, booleans hold yes/no values
 *
 * COMMON DATA TYPES IN JAVASCRIPT:
 * - String: Text values like "Malé", "Ahmed", "Dhivehi"
 * - Number: Numeric values like 26, 1192, 3.14
 * - Boolean: True or false values
 * - Array: Lists of values like ["Malé", "Hulhumalé", "Vilimalé"]
 * - Object: Complex data with properties like {name: "Ahmed", age: 25}
 * - Null: Intentionally empty value
 * - Undefined: Variable declared but not assigned
 *
 * SPECIAL NUMBER VALUES:
 * - Infinity: Result of dividing by zero → 5 / 0 = Infinity
 * - -Infinity: Negative infinity → -5 / 0 = -Infinity
 * - NaN (Not-a-Number): Invalid math result or failed conversion
 *   Examples: Number("hello") = NaN, 0 / 0 = NaN, "text" * 5 = NaN
 *   Note: typeof NaN is "number" (confusing but true!)
 *   Check with: Number.isNaN(value)
 *
 * REAL-WORLD EXAMPLE:
 * When storing a student's information:
 *   - Name is a STRING: "Aishath"
 *   - Age is a NUMBER: 18
 *   - Is enrolled is a BOOLEAN: true
 *   - Subjects is an ARRAY: ["Math", "Science", "Dhivehi"]
 *   - Full profile is an OBJECT: {name: "Aishath", age: 18, subjects: [...]}
 */

