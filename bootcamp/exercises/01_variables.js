/*
 * WHAT ARE VARIABLES?
 * Variables are containers that store data values in your program.
 * Think of them like labeled boxes where you can store information.
 *
 * WHY DO WE NEED VARIABLES?
 * 1. Store Information: Keep track of data like names, numbers, or settings
 * 2. Reuse Values: Use the same data multiple times without repeating it
 * 3. Make Changes Easy: Update a value in one place instead of everywhere
 * 4. Make Code Readable: Give meaningful names to data (e.g., "fishermanName" instead of just "Hassan")
 *
 * REAL-WORLD EXAMPLE:
 * Instead of writing "Hassan" 50 times in your program, store it once:
 *   let fishermanName = "Hassan";
 * Now you can use `fishermanName` everywhere, and if the name changes,
 * you only update it in one place!
 */

